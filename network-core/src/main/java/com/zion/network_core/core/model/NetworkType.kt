/**
 * 网络类型枚举
 */
enum class NetworkType {
    /**
     * WiFi 网络
     */
    WIFI,

    /**
     * 2G 移动网络
     */
    MOBILE_2G,

    /**
     * 3G 移动网络
     */
    MOBILE_3G,

    /**
     * 4G 移动网络
     */
    MOBILE_4G,

    /**
     * 5G 移动网络
     */
    MOBILE_5G,

    /**
     * 以太网
     */
    ETHERNET,

    /**
     * 未知网络类型
     */
    UNKNOWN
}